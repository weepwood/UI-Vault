import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const foundation=JSON.parse(fs.readFileSync(path.join(root,'tokens/foundation.json'),'utf8'));
const palette=JSON.parse(fs.readFileSync(path.join(root,'tokens/themes.json'),'utf8'));
const out=path.join(root,'dist');
fs.mkdirSync(out,{recursive:true});
const direct={};
for(const group of ['space','radius','type','motion','size']){
 for(const [key,val] of Object.entries(foundation[group])){
  if(key.startsWith('$'))continue;
  if(!val || typeof val.$value!=='string')throw new Error('缺少 Token '+group+'.'+key);
  direct['--ui-'+group+'-'+key.replace(/[A-Z]/g,c=>'-'+c.toLowerCase())]=val.$value;
 }
}
const decl=obj=>Object.entries(obj).map(([k,v])=>'  '+(k.startsWith('--')?k:'--ui-'+k)+': '+v+';').join('\n');
const theme=(name,accent)=>({...palette.themes[name],...palette.accents[accent][name]});
const block=(selector,vals)=>selector+' {\n'+decl(vals)+'\n}\n\n';
let css='/* Generated by scripts/build-tokens.mjs; edit tokens/*.json instead. */\n:root {\n'+decl(direct)+'\n  --ui-font-sans: Inter, -apple-system, BlinkMacSystemFont, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif;\n  --ui-shadow-popover: 0 18px 60px rgba(18, 27, 43, .13), 0 2px 12px rgba(18, 27, 43, .06);\n  --ui-ease: cubic-bezier(.2,.7,.2,1);\n  --ui-row-height: var(--ui-size-control);\n}\n\n';
css+=block(':root, [data-theme="light"]',theme('light','indigo'));
css+=block('[data-theme="dark"]',theme('dark','indigo'));
css+='@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]):not([data-theme="dark"]) {\n'+decl(theme('dark','indigo')).split('\n').map(x=>'  '+x).join('\n')+'\n  }\n}\n\n';
for(const [accent,modes] of Object.entries(palette.accents)){
 css+=block('[data-accent="'+accent+'"]:not([data-theme="dark"])',modes.light);
 css+=block('[data-accent="'+accent+'"][data-theme="dark"]',modes.dark);
 css+='@media (prefers-color-scheme: dark) {\n  [data-accent="'+accent+'"]:not([data-theme="light"]):not([data-theme="dark"]) {\n'+decl(modes.dark).split('\n').map(x=>'  '+x).join('\n')+'\n  }\n}\n\n';
}
css+='[data-density="compact"] { --ui-row-height: 30px; }\n';
fs.writeFileSync(path.join(out,'theme.css'),css);
fs.writeFileSync(path.join(out,'tokens.json'),JSON.stringify({foundation,...palette},null,2)+'\n');
fs.writeFileSync(path.join(out,'tokens.ts'),'// Generated; do not edit.\nexport const foundationTokens = '+JSON.stringify(foundation,null,2)+' as const;\nexport const semanticTokens = '+JSON.stringify(palette,null,2)+' as const;\nexport type ThemeName = keyof typeof semanticTokens.themes;\nexport type AccentName = keyof typeof semanticTokens.accents;\n');
const rustKey=k=>(/^[0-9]/.test(k)?'S'+k:k).replace(/([a-z0-9])([A-Z])/g,'$1_$2').replace(/-/g,'_').toUpperCase();
const rustGroup=(name,vals,depth)=>' '.repeat(depth)+'pub mod '+(name==='type'?'typography':name)+' {\n'+Object.entries(vals).filter(([k])=>!k.startsWith('$')).map(([k,v])=>' '.repeat(depth+4)+'pub const '+rustKey(k)+': &str = '+JSON.stringify(v.$value)+';').join('\n')+'\n'+' '.repeat(depth)+'}\n';
let rs='// Generated. Parse these strings into GPUI types at the adapter boundary.\npub mod ui_tokens {\n';
for(const k of ['space','radius','type','motion','size'])rs+=rustGroup(k,foundation[k],4);
for(const mode of ['light','dark']){
 const vals=theme(mode,'indigo');rs+='    pub mod '+mode+' {\n'+Object.entries(vals).map(([k,v])=>'        pub const '+rustKey(k)+': &str = '+JSON.stringify(v)+';').join('\n')+'\n    }\n';
}
rs+='    pub mod accents {\n';
for(const [name,modes] of Object.entries(palette.accents)){
 rs+='        pub mod '+name+' {\n';
 for(const mode of ['light','dark'])rs+='            pub mod '+mode+' {\n'+Object.entries(modes[mode]).map(([k,v])=>'                pub const '+rustKey(k)+': &str = '+JSON.stringify(v)+';').join('\n')+'\n            }\n';
 rs+='        }\n';
}
rs+='    }\n}\n';
fs.writeFileSync(path.join(out,'tokens.rs'),rs);
console.log('Built '+Object.keys(direct).length+' foundation tokens and '+Object.keys(palette.accents).length+' accents.');
